'use strict';
/**
 * Copies the web dashboard into the FiveM resource (resource/AdvancedAC/html/panel) so the in-game
 * /adv panel is the exact same app. Run after any dashboard change:   npm run build:nui
 */
const fs = require('fs');
const path = require('path');

const pub = path.join(__dirname, '..', 'public');
const out = path.join(__dirname, '..', '..', 'resource', 'AdvancedAC', 'html', 'panel');

fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(out, { recursive: true });
fs.cpSync(path.join(pub, 'assets'), path.join(out, 'assets'), {
  recursive: true,
  filter: (src) => !src.includes(`${path.sep}map${path.sep}`) && !src.endsWith('appeal.js') && !src.endsWith(`${path.sep}map`),
});
const sioDir = path.dirname(require.resolve('socket.io/package.json'));
fs.copyFileSync(path.join(sioDir, 'client-dist', 'socket.io.min.js'), path.join(out, 'socket.io.min.js'));

fs.writeFileSync(path.join(out, 'index.html'), `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8" />
  <title>Sentinel AC</title>
  <link rel="stylesheet" href="assets/css/app.css" />
</head>
<body class="nui">
  <div id="root"></div>
  <div id="toasts"></div>
  <script src="socket.io.min.js"></script>
  <script src="bridge.js"></script>
</body>
</html>
`);

// The parent NUI page sends the backend URL + a bearer session issued by the game server.
fs.writeFileSync(path.join(out, 'bridge.js'), `'use strict';
// GENERATED by backend/src/build-nui.js
(function () {
  var started = false;
  window.addEventListener('message', function (e) {
    var m = e.data || {};
    if (m.type !== 'sac:config' || started) return;
    started = true;
    window.SAC_NUI = { apiBase: m.apiBase, token: m.token, serverId: m.serverId };
    import('./assets/js/app.js');
  });
  window.parent.postMessage({ type: 'sac:ready' }, '*');
})();
`);

let n = 0;
(function count(d) { for (const f of fs.readdirSync(d, { withFileTypes: true })) f.isDirectory() ? count(path.join(d, f.name)) : n++; })(out);
console.log(`in-game panel built: ${n} files -> ${out}`);
